def _clamp(reg_modrm: int) -> bytes:
    """movsx reg, word [0x80083C]; cmp reg, 12; jle +5; mov reg, 12; ret"""
    r = (reg_modrm >> 3) & 7
    return (bytes([0x0F, 0xBF, reg_modrm]) + struct.pack('<I', 0x80083C) + bytes([0x83, 0xF8 | r, 0x0C, 0x7E, 0x05, 0xB8 | r])
            + struct.pack('<I', 12) + b'\xc3')


